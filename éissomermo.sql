    <h2>Modo de preparo da lasanha</h2>

    <h3>Ingredientes:</h3>
    <ul>
        <li>Massa de lasanha</li>
        <li>Carne moída</li>
        <li>Molho de tomate</li>
        <li>Queijo mussarela</li>
        <li>Presunto</li>
        <li>Sal e temperos</li>
    </ul>

    <h3>Modo de preparo:</h3>
    <p>
        Primeiro, cozinhe a carne moída com temperos e adicione o molho de tomate.
        Depois, em uma travessa, monte camadas alternando massa, carne, presunto e queijo.
        Repita as camadas até acabar os ingredientes.
        Por fim, leve ao forno por cerca de 30 minutos até o queijo derreter e dourar.
    </p>

